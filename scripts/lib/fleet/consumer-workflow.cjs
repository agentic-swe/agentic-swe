'use strict';

const fs = require('node:fs');
const path = require('node:path');

/**
 * Build GitHub Actions workflow for consumer fleet evidence collection.
 * @param {{ projectRoot: string, pluginRoot: string }} opts
 */
function buildConsumerFleetWorkflowYaml(opts) {
  const projectRoot = path.resolve(opts.projectRoot);
  const pluginRoot = path.resolve(opts.pluginRoot);
  let relPlugin = path.relative(projectRoot, pluginRoot);
  if (!relPlugin || relPlugin === '.') relPlugin = '../agentic-swe';
  relPlugin = relPlugin.replace(/\\/g, '/');

  return `# Generated by agentic-swe fleet-onboard --write-workflow
# Collect fleet muscle-memory evidence (independent class). Upload artifact and send to maintainer.
name: agentic-swe fleet evidence

on:
  workflow_dispatch:

jobs:
  fleet-evidence:
    runs-on: ubuntu-latest
    env:
      AGENTIC_SWE_PROJECT_ROOT: \${{ github.workspace }}
      AGENTIC_SWE_FLEET_EVIDENCE_CLASS: independent
      AGENTIC_SWE_EVOLVE_ON_STOP: '1'
      AGENTIC_SWE_PLUGIN_ROOT: \${{ vars.AGENTIC_SWE_PLUGIN_ROOT || '${relPlugin}' }}

    steps:
      - uses: actions/checkout@v4

      - uses: actions/setup-node@v4
        with:
          node-version: '22'

      - name: Install agentic-swe plugin dependencies
        working-directory: \${{ env.AGENTIC_SWE_PLUGIN_ROOT }}
        run: npm ci

      - name: Fleet onboard and submit
        working-directory: \${{ env.AGENTIC_SWE_PLUGIN_ROOT }}
        run: |
          npm run fleet-onboard -- --project-root "\$AGENTIC_SWE_PROJECT_ROOT" --skip-sessions --json
          npm run fleet-submit -- --project-root "\$AGENTIC_SWE_PROJECT_ROOT" --out "\$AGENTIC_SWE_PROJECT_ROOT/fleet-submission.json"

      - uses: actions/upload-artifact@v4
        with:
          name: fleet-submission
          path: fleet-submission.json
          if-no-files-found: error
`;
}

/**
 * Write .github/workflows/agentic-swe-fleet.yml into consumer repo.
 * @param {{ projectRoot: string, pluginRoot: string, force?: boolean }} opts
 */
function writeConsumerFleetWorkflow(opts) {
  const projectRoot = path.resolve(opts.projectRoot);
  const pluginRoot = path.resolve(opts.pluginRoot);
  const workflowDir = path.join(projectRoot, '.github', 'workflows');
  const workflowPath = path.join(workflowDir, 'agentic-swe-fleet.yml');

  if (fs.existsSync(workflowPath) && !opts.force) {
    return {
      ok: false,
      skipped: true,
      workflow_path: workflowPath,
      error: 'workflow exists (pass force: true to overwrite)',
    };
  }

  fs.mkdirSync(workflowDir, { recursive: true });
  const yaml = buildConsumerFleetWorkflowYaml({ projectRoot, pluginRoot });
  fs.writeFileSync(workflowPath, yaml);

  return {
    ok: true,
    workflow_path: workflowPath,
    plugin_root_relative: path.relative(projectRoot, pluginRoot).replace(/\\/g, '/') || '../agentic-swe',
    measurement_contract:
      'Consumer workflow uses fleet_evidence_class=independent. Set vars.AGENTIC_SWE_PLUGIN_ROOT if plugin is not at the default relative path.',
  };
}

module.exports = { buildConsumerFleetWorkflowYaml, writeConsumerFleetWorkflow };
